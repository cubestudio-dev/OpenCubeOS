    rows.append('#include "types.h"')
    rows.append("")
    rows.append("/* Glyphs 0x00-0x1F and 0x7F-0xFF default to a 'missing glyph' box. */")
    rows.append("const u8 oc_font8x16[256][16] = {")
    for cp in range(256):
        g = glyph_for(cp)
        hexbytes = ",".join(f"0x{b:02X}" for b in g)
        rows.append(f"    /* 0x{cp:02X} */ {{ {hexbytes} }},")
    rows.append("};")
    rows.append("")
    with open(out_path, "w") as f:
        f.write("\n".join(rows))
    print(f"wrote {out_path} ({256} glyphs, {256*16} bytes)")

