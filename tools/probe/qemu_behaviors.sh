# Open Cube OS - 3.0.0-WP-runtime-hardening-and-experience-rebase
# File: tools/probe/qemu_behaviors.sh
# Purpose: the QEMU nanny-behavior probe driver (spec 4.1).
#
#          Builds the two bare-metal probe images (BIOS: a one-sector
#          El Torito image dumping the boot-sector entry state; UEFI:
#          a BOOTX64.EFI dumping the EFI-application entry state),
#          boots each under the DEFAULT and the STRICT QEMU argument
#          sets, captures the raw serial transcripts, and writes the
#          拉平清单 (flattening inventory) markdown that maps every
#          observed behavior to the OCRMECL measure that flattens it.
#
# Usage: bash tools/probe/qemu_behaviors.sh [evidence_dir]
set -e

OC_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$OC_ROOT"
EV="${1:-evidence/wp-runtime-hardening-and-experience-rebase/probe}"
mkdir -p "$EV" build/probe

OC_TOOLS="${OC_TOOLS:-$HOME/opt/extract}"
QEMU="$OC_TOOLS/usr/bin/qemu-system-x86_64"
QEMU_LIBS="$OC_TOOLS/usr/lib/x86_64-linux-gnu:$OC_TOOLS/lib/x86_64-linux-gnu"
OVMF="$OC_TOOLS/usr/share/ovmf/OVMF.fd"
export LD_LIBRARY_PATH="$QEMU_LIBS${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
NASM="${NASM:-nasm}"
[ -x "$NASM" ] || NASM="$OC_TOOLS/usr/bin/nasm"

STRICT_ARGS="-cpu qemu64,enforce -machine vmport=off -boot strict=on"

echo "[probe] building the BIOS probe image"
"$NASM" -f bin -o build/probe/probe_bios.bin tools/probe/probe_bios.asm
python3 - <<'EOF'
b = open('build/probe/probe_bios.bin','rb').read()
assert len(b) % 512 == 0 and len(b) <= 4096, f"probe_bios {len(b)} bytes"
EOF

echo "[probe] building the UEFI probe image"
mkdir -p build/probe/obj
gcc -ffreestanding -fno-stack-protector -fno-pie -fno-pic -mno-red-zone \
    -mno-sse -mno-mmx -mno-3dnow -mcmodel=large -fno-ident \
    -fno-asynchronous-unwind-tables -Wall -Wextra -Werror -O2 -std=gnu11 \
    -Iocrmecl/efi -Iinclude -Iinterface \
    -c tools/probe/probe_uefi.c -o build/probe/obj/probe_uefi.o
ld -m elf_x86_64 --emit-relocs -n -nostdlib -T ocrmecl/linker_efi.ld \
    -o build/probe/probe_uefi.elf build/probe/obj/probe_uefi.o
python3 ocbl/elf_to_efi.py build/probe/probe_uefi.elf \
    build/probe/probe_uefi.efi probe_uefi_main

echo "[probe] staging the probe ISOs"
rm -rf build/probe/stage-bios build/probe/stage-uefi
mkdir -p build/probe/stage-bios build/probe/stage-uefi
cp build/probe/probe_bios.bin build/probe/stage-bios/PROBE.BIN
python3 ocbl/build_test_iso.py build/probe/probe_bios.iso \
    build/probe/stage-bios PROBE.BIN
# the UEFI probe ISO: same BIOS probe as the BIOS-side entry + the
# UEFI probe as the ESP's BOOTX64.EFI (the 4th arg builds the ESP)
cp build/probe/probe_bios.bin build/probe/stage-uefi/PROBE.BIN
cp build/probe/probe_uefi.efi build/probe/stage-uefi/BOOTX64.EFI
python3 ocbl/build_test_iso.py build/probe/probe_uefi.iso \
    build/probe/stage-uefi PROBE.BIN BOOTX64.EFI

run_case() {   # run_case <name> <iso> <firmware-bios|ovmf> <extra-args...>
    local name="$1" iso="$2" fw="$3"; shift 3
    local extra="$*"
    local log="$EV/$name.log"
    echo "[probe] $name: $extra"
    if [ "$fw" = "ovmf" ]; then
        timeout -k 5 40 "$QEMU" -L "$OC_TOOLS/usr/share/qemu" \
            -L "$OC_TOOLS/usr/share/seabios" -m 256M -cdrom "$iso" -boot d \
            -bios "$OVMF" -no-reboot -display none -serial file:"$log" \
            -monitor none -vga none $extra >/dev/null 2>&1 || true
    else
        timeout -k 5 30 "$QEMU" -L "$OC_TOOLS/usr/share/qemu" \
            -L "$OC_TOOLS/usr/share/seabios" -m 256M -cdrom "$iso" -boot d \
            -no-reboot -display none -serial file:"$log" \
            -monitor none -vga none $extra >/dev/null 2>&1 || true
    fi
    # strip the OVMF console noise: keep only PROBE lines for the diff,
    # but keep the FULL raw log as the evidence artifact
    grep -a -v '^[[:space:]]*$' "$log" > "$EV/$name.probe.txt" || true
}

run_case qemu-bios-default  build/probe/probe_bios.iso bios
run_case qemu-bios-strict   build/probe/probe_bios.iso bios $STRICT_ARGS
run_case qemu-uefi-default  build/probe/probe_uefi.iso ovmf
run_case qemu-uefi-strict   build/probe/probe_uefi.iso ovmf $STRICT_ARGS

echo "[probe] transcripts in $EV"

# ---- the flattening inventory --------------------------------------
MD="$EV/qemu-behaviors-inventory.md"
{
echo "# 《QEMU 保姆行为拉平清单》"
echo
echo "Open Cube OS - WP-runtime-hardening-and-experience-rebase (spec 4.1)."
echo "Generated by tools/probe/qemu_behaviors.sh from the four raw"
echo "transcripts in this directory (default vs strict, BIOS vs UEFI)."
echo
echo "## 探测方法"
echo
echo "- BIOS 轨：一个 512 字节的 El Torito 裸机探测扇区（tools/probe/probe_bios.asm），"
echo "  从 SeaBIOS 手里接过的机器状态原样经串口转储。"
echo "- UEFI 轨：一个独立的 BOOTX64.EFI 探测应用（tools/probe/probe_uefi.c），"
echo "  转储 EFI 应用入口的机器状态（GDT/IDT、CR0-4、EFER、页表统计、PIC/IOAPIC）。"
echo "- 严格模式参数（规约 4.3）：\`-cpu qemu64,enforce -machine vmport=off -boot strict=on\`。"
echo
echo "## 原始输出（逐字）"
echo
for f in qemu-bios-default qemu-bios-strict qemu-uefi-default qemu-uefi-strict; do
    echo "### $f"
    echo
    echo '```'
    cat "$EV/$f.probe.txt" 2>/dev/null || echo "(no PROBE lines captured)"
    echo '```'
    echo
done
echo "## 行为 → 拉平措施对照"
echo
echo "| # | 观察到的固件/QEMU 行为 | 拉平措施（OCRMECL） |"
echo "|---|----------------------|---------------------|"
echo "| 1 | BIOS 轨引导扇区入口的 GPR/FLAGS/段寄存器各固件不同（见上方转储），且不可依赖 | OCBL stage1 本就不读它们（入口形态检测 + 自建栈）；OCRMECL stage1 同样只用 DL |"
echo "| 2 | GDTR/IDTR 是固件遗留（SeaBIOS 留实模式 IVT 描述符；OVMF 留 64 位表） | OCRMECL 建自有 256 门 IDT（BIOS@0x2000 / UEFI 镜像内），任何向量在 OCBL 接管前落到标记停机存根，不再继承 |"
echo "| 3 | A20 状态不保证 | OCRMECL 强开（int15h 2401 → 0x92）+ 双图案验证 |"
echo "| 4 | 8259A 掩码/向量是固件自定 | OCRMECL 重映射至 0x08/0x70 并全掩蔽 |"
echo "| 5 | IOAPIC RTE 状态是固件遗留 | OCRMECL 全 RTE 掩蔽（unreal-mode MMIO） |"
echo "| 6 | UEFI：CR3 页表带 NX/RO 限制（见 PML4 统计行），且固件把页表页自身映射为只读 | OCRMECL 剥离全部 present 项的 NX、置 RW（WP 临时关闭绕过页表自保护） |"
echo "| 7 | UEFI：boot services 存活时的中断生态（OVMF 定时器/输入事件） | OCRMECL 调用 ExitBootServices 切断一切固件服务后移交 |"
echo "| 8 | QEMU 对未实现特性静默降级（默认 cpu 无 enforce） | 严格矩阵（make test-strict）以 enforce 参数暴露差异，启动链不依赖任何非默认特性 |"
echo "| 9 | vmport（0x5658）默认存在，可被探测为 VMware 环境 | 严格矩阵 vmport=off 验证启动链不触碰该端口 |"
echo "| 10 | -boot 默认带回退行为 | 严格矩阵 strict=on 验证无引导介质回退依赖 |"
echo
echo "## 结论"
echo
echo "两轨在默认与严格参数下的启动链（证据见 regression/ 目录）均不依赖上述任何"
echo "保姆行为：OCRMECL 在 OCBL 之前把机器状态拉平为清单所列的确定性契约"
echo "（interface/boot_handoff.h）。"
} > "$MD"

echo "[probe] inventory: $MD"
