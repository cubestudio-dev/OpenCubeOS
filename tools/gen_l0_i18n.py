"""
gen_l0_i18n.py: regenerate src/L0/core/lib/l0_i18n_data.c from
etc/i18n/l0/{en,zh}.json.

3.0.0-WP06g2: the L0-side i18n resource.  Kernel-service user-facing
strings live in the two JSON files (English default + Chinese); this
generator emits the key-sorted lookup tables the l0_tr_() runtime
(src/L0/core/lib/l0_i18n.c) binary-searches.  The generated file is
committed (the userprogs_data.h pattern) so a fresh wildcard build
always sees it; the Makefile rule regenerates it when a resource or
this script changes.

The Chinese text is UTF-8 in the .c - the kernel console renders
UTF-8 through console_cn since WP-06g1 (same path the ush editor
uses), and the serial tee mirrors the bytes.

Usage: python3 tools/gen_l0_i18n.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES_DIR = os.path.join(ROOT, "etc", "i18n", "l0")
OUT = os.path.join(ROOT, "src", "L0", "core", "lib", "l0_i18n_data.c")


def fail(msg):
    print(f"gen_l0_i18n: FAIL: {msg}", file=sys.stderr)
    sys.exit(1)


def c_escape(s):
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    return "".join(out)


def load(path):
    with open(path, "r", encoding="utf-8") as f:
        d = json.load(f)
    if not isinstance(d, dict):
        fail(f"{path} must be a flat object")
    for k, v in d.items():
        if not isinstance(k, str) or not isinstance(v, str):
            fail(f"{path}: keys and values must be strings ({k!r})")
    return d


def table(d):
    items = sorted(d.items())
    rows = ",\n".join(
        f'    {{ "{c_escape(k)}", "{c_escape(v)}" }}' for k, v in items)
    return "{\n" + rows + "\n}"


def main():
    en = load(os.path.join(RES_DIR, "en.json"))
    zh = load(os.path.join(RES_DIR, "zh.json"))
    missing = sorted(set(en) - set(zh))
    if missing:
        fail(f"zh.json is missing keys present in en.json: {missing}")
    text = (
        "/* SPDX-License-Identifier: Apache-2.0 */\n"
        "/* Copyright 2026 cubestudio-dev <cubestudio@qq.com> */\n"
        "/* Auto-generated by tools/gen_l0_i18n.py - DO NOT EDIT.\n"
        " * Source resources: etc/i18n/l0/en.json + etc/i18n/l0/zh.json.\n"
        " * Tables are key-sorted; l0_tr_() binary-searches them. */\n"
        '#include "l0_i18n.h"\n'
        "\n"
        f"const struct l0_i18n_kv L0_I18N_EN[] = {table(en)};\n"
        f"const int L0_I18N_EN_N = {len(en)};\n"
        f"const struct l0_i18n_kv L0_I18N_ZH[] = {table(zh)};\n"
        f"const int L0_I18N_ZH_N = {len(zh)};\n"
    )
    # Idempotent emit (same discipline as gen_userprogs.py): keep the
    # mtime when the bytes match so incremental builds stay quiet.
    old = None
    try:
        with open(OUT, "r", encoding="utf-8") as f:
            old = f.read()
    except OSError:
        pass
    if old == text:
        print(f"gen_l0_i18n: {OUT} unchanged (mtime kept)")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"gen_l0_i18n: {len(en)} keys -> {OUT}")


if __name__ == "__main__":
    main()
