"""
gen_l1svc_ops.py: mirror the kernel-side L1SVC numbering into the ring-3
app library (src/L1/_shared/l1svc_ops.h).

Single source of truth: src/L0/services/sysapi/l1svc_defs.h.  Every
#define L1SVC_* line is copied verbatim, so ring-3 wrapper apps pick the
same numbers the kernel dispatches on.  Renumbering upstream stays
append-only; this mirror regenerates mechanically.

Called by tools/gen_userprogs.py before building app folders.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "L0", "services", "sysapi", "l1svc_defs.h")
DST = os.path.join(ROOT, "src", "L1", "_shared", "l1svc_ops.h")


def main():
    if not os.path.exists(SRC):
        print("gen_l1svc_ops: missing source header", file=sys.stderr)
        sys.exit(1)
    src = open(SRC).read()
    # Every single-line OBJECT L1SVC_* definition, verbatim (with its
    # trailing comment).  Function macros (L1SVC_CAT_NAME) are kernel-side
    # routing helpers - the app side never expands them, and their
    # multi-line bodies would break a verbatim copy; skipped deliberately.
    lines = []
    src_lines = src.splitlines()
    i = 0
    while i < len(src_lines):
        raw = src_lines[i].rstrip()
        i += 1
        if not re.match(r"\s*#define\s+L1SVC_[A-Z0-9_]+[\s(]", raw):
            continue
        if "(" in raw.split()[1]:   # function macro -> skip
            continue
        # Absorb the whole (possibly multi-line) trailing comment so an
        # unterminated /* can never leak into the mirror header.
        line = raw
        while "/*" in line and ("*/" not in line or
                                line.index("/*") > line.rindex("*/")):
            if i >= len(src_lines):
                break
            line = line + "\n" + src_lines[i].rstrip()
            i += 1
        if line.endswith("\\"):  # multiline object macro -> skip
            continue
        lines.append(line)
    out = []
    out.append("/* SPDX-License-Identifier: Apache-2.0 */")
    out.append("/* Copyright 2026 cubestudio-dev <cubestudio@qq.com> */")
    out.append("/* Auto-generated by tools/gen_l1svc_ops.py - DO NOT EDIT.")
    out.append(" * Verbatim mirror of src/L0/services/sysapi/l1svc_defs.h")
    out.append(" * (the numbering contract; renumber upstream only by")
    out.append(" * appending, then regenerate this mirror). */")
    out.append("#ifndef OC_L1SVC_OPS_MIRROR_H")
    out.append("#define OC_L1SVC_OPS_MIRROR_H")
    out.append("")
    out.extend(lines)
    out.append("")
    out.append("#endif /* OC_L1SVC_OPS_MIRROR_H */")
    text = "\n".join(out) + "\n"
    with open(DST, "w") as f:
        f.write(text)
    print(f"gen_l1svc_ops: {len(lines)} constants -> {DST}")


if __name__ == "__main__":
    main()
