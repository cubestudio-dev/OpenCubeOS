/* ---- helpers -------------------------------------------------------- */

static int t_pass = 0, t_total = 0;

static void case_begin(const char *name) {
    oc_console_puts("[");
    oc_console_puts(name);
    oc_console_puts("] ");
}

static void case_result(int ok) {
    t_total++;
    if (ok) t_pass++;
    oc_console_puts(ok ? "PASS\n" : "FAIL\n");
}

static void case_info(const char *label, long value) {
    char info[80];
    char num[16];
    oc_strcpy(info, label);
    if (value < 0) {
        oc_strcat(info, "-");
        oc_u64_to_str((u64)(-value), num);
    } else {
        oc_u64_to_str((u64)value, num);
    }
    oc_strcat(info, num);
    oc_console_puts(info);
    oc_console_puts(" ");
}

/* accumulate sink for streaming cases (file-scope: C has no closures) */
static u8  *g_acc_out;
static int  g_acc_len;
static int  g_acc_cap;

static int acc_sink(void *ctx, const u8 *data, int n) {
    (void)ctx;
    if (g_acc_len + n > g_acc_cap) return -1;
    for (int i = 0; i < n; i++) g_acc_out[g_acc_len++] = data[i];
    return 0;
}

/* ---- shared package-file location ------------------------------------ */

static const char *downloaded_package_path(void) {
    vfs_stat_t st;
    if (vfs_stat(OC_UPDATE_PKG_PATH, &st) == 0 && st.size > 0)
        return OC_UPDATE_PKG_PATH;
    if (vfs_stat(OC_UPDATE_PKG_TMP, &st) == 0 && st.size > 0)
        return OC_UPDATE_PKG_TMP;
    return NULL;
}

/* ---- ustar header builder (tar parser unit cases) -------------------- */

static void tar_put_octal(char *dst, int width, u64 v) {
    char tmp[24];
    int i = 0;
    if (v == 0) tmp[i++] = '0';
    while (v > 0) { tmp[i++] = (char)('0' + (v & 7)); v >>= 3; }
    int p = 0;
    for (int z = 0; z < width - 1 - i; z++) dst[p++] = '0';
    while (i > 0) dst[p++] = tmp[--i];
    dst[p] = 0;
}

static void tar_build_header(u8 *blk, const char *name, u64 size, char type) {
    oc_memset(blk, 0, 512);
    oc_strncpy((char *)blk, name, 99);
    oc_memcpy(blk + 100, "0000644\0", 8);
    oc_memcpy(blk + 108, "0000000\0", 8);
    oc_memcpy(blk + 116, "0000000\0", 8);
    char sz[13];
    tar_put_octal(sz, 12, size);
    oc_memcpy(blk + 124, sz, 12);
    oc_memcpy(blk + 136, "00000000000\0", 12);
    oc_memset(blk + 148, ' ', 8);
    blk[156] = (u8)type;
    oc_memcpy(blk + 257, "ustar\0", 6);
    oc_memcpy(blk + 263, "00", 2);
    u32 sum = 0;
    for (int i = 0; i < 512; i++) sum += blk[i];
    char cs[9];
    tar_put_octal(cs, 8, sum);
    oc_memcpy(blk + 148, cs, 7);
    blk[155] = 0;
}

typedef struct {
    char   name[128];
    u64    size;
    u8     data[256];
    int    files;
} tar_acc_t;

static int tar_acc_cb(void *ctx, const char *path, int type, u64 size,
                      const u8 *data, int len) {
    tar_acc_t *a = (tar_acc_t *)ctx;
    if (type == OC_TAR_DIR) return 0;
    if (data == NULL && len == 0) return 0;      /* final slice */
    oc_strncpy(a->name, path, sizeof(a->name) - 1);
    a->size = size;
    a->files++;
    if (data && len <= (int)sizeof(a->data)) {
        oc_memcpy(a->data, data, len);
    }
    return 0;
}

/* ==================================================================== */
/* update_pkg_test: gzip/DEFLATE + tar unit tests                        */
/* ==================================================================== */

int cmd_update_pkg_test(const char *args) {
    (void)args;
    t_pass = 0; t_total = 0;
    oc_console_puts("[update_pkg_test] gzip/DEFLATE + tar unit tests\n");

    u8 *out = (u8 *)kmalloc(GZV_PAYLOAD_LEN + 64);
    if (!out) {
        oc_console_puts("[update_pkg_test] out of memory\n");
        return 1;
    }

    /* 1..7: one-shot gunzip over every block type / header option */
    {
        int n = oc_gunzip(GZV_stored_GZ, (int)sizeof(GZV_stored_GZ),
                          out, GZV_PAYLOAD_LEN + 64);
        case_begin("gunzip stored block");
        int ok = (n == GZV_PAYLOAD_LEN &&
                  oc_memcmp(out, GZV_PAYLOAD_EXPECTED, GZV_PAYLOAD_LEN) == 0);
        case_info("exp=1280 got=", n);
        case_result(ok);
    }
    {
        int n = oc_gunzip(GZV_fixed_GZ, (int)sizeof(GZV_fixed_GZ),
                          out, GZV_PAYLOAD_LEN + 64);
        case_begin("gunzip fixed huffman block");
        int ok = (n == GZV_PAYLOAD_LEN &&
                  oc_memcmp(out, GZV_PAYLOAD_EXPECTED, GZV_PAYLOAD_LEN) == 0);
        case_info("exp=1280 got=", n);
        case_result(ok);
    }
    {
        int n = oc_gunzip(GZV_dynamic_GZ, (int)sizeof(GZV_dynamic_GZ),
                          out, GZV_PAYLOAD_LEN + 64);
        case_begin("gunzip dynamic huffman block");
        int ok = (n == GZV_PAYLOAD_LEN &&
                  oc_memcmp(out, GZV_PAYLOAD_EXPECTED, GZV_PAYLOAD_LEN) == 0);
        case_info("exp=1280 got=", n);
        case_result(ok);
    }
    {
        int n = oc_gunzip(GZV_tiny_GZ, (int)sizeof(GZV_tiny_GZ), out, 64);
        case_begin("gunzip tiny (no matches)");
        int ok = (n == GZV_TINY_LEN &&
                  oc_memcmp(out, GZV_TINY_EXPECTED, GZV_TINY_LEN) == 0);
        case_info("exp=6 got=", n);
        case_result(ok);
    }
    {
        int n = oc_gunzip(GZV_fname_GZ, (int)sizeof(GZV_fname_GZ),
                          out, GZV_PAYLOAD_LEN + 64);
        case_begin("gzip header FNAME");
        case_info("exp=1280 got=", n);
        case_result(n == GZV_PAYLOAD_LEN);
    }
    {
        int n = oc_gunzip(GZV_fextra_GZ, (int)sizeof(GZV_fextra_GZ),
                          out, GZV_PAYLOAD_LEN + 64);
        case_begin("gzip header FEXTRA");
        case_info("exp=1280 got=", n);
        case_result(n == GZV_PAYLOAD_LEN);
    }
    {
        int n = oc_gunzip(GZV_both_GZ, (int)sizeof(GZV_both_GZ),
                          out, GZV_PAYLOAD_LEN + 64);
        case_begin("gzip header FEXTRA+FNAME");
        case_info("exp=1280 got=", n);
        case_result(n == GZV_PAYLOAD_LEN);
    }
    kfree(out);

    /* 8: corrupted CRC must fail */
    {
        case_begin("corrupted CRC32 rejected");
        u8 *out2 = (u8 *)kmalloc(8192);
        int n = oc_gunzip(GZV_BCRC_GZ, (int)sizeof(GZV_BCRC_GZ),
                          out2, 8192);
        kfree(out2);
        case_result(n == OC_GZIP_ERR_CRC);
    }
    /* 9: truncated stream must fail */
    {
        case_begin("truncated stream rejected");
        u8 out2[64];
        int n = oc_gunzip(GZV_TRUNC_GZ, (int)sizeof(GZV_TRUNC_GZ),
                          out2, (int)sizeof(out2));
        case_result(n < 0);
    }
    /* 10: chunked streaming feed (1-byte chunks, resume coverage) */
    {
        g_acc_out = (u8 *)kmalloc(GZV_PAYLOAD_LEN + 64);
        g_acc_len = 0;
        g_acc_cap = GZV_PAYLOAD_LEN + 64;
        oc_gzip_t *g = (oc_gzip_t *)kmalloc(sizeof(oc_gzip_t));
        oc_memset(g, 0, sizeof(*g));
        case_begin("streaming resume (1-byte chunks)");
        int okr = (oc_gzip_init(g, acc_sink, NULL) == 0);
        for (int i = 0; okr && i < (int)sizeof(GZV_dynamic_GZ); i++) {
            if (oc_gzip_feed(g, &GZV_dynamic_GZ[i], 1) != 0) { okr = 0; break; }
        }
        if (okr) okr = (oc_gzip_finish(g) == 0);
        if (okr) okr = (g_acc_len == GZV_PAYLOAD_LEN);
        if (okr) okr = (oc_memcmp(g_acc_out, GZV_PAYLOAD_EXPECTED,
                                  GZV_PAYLOAD_LEN) == 0);
        case_info("out=", g_acc_len);
        kfree(g);
        kfree(g_acc_out);
        g_acc_out = NULL;
        case_result(okr);
    }
    /* 11: tar parser roundtrip */
    {
        case_begin("ustar parse (name/size/content)");
        u8 *stream = (u8 *)kmalloc(512 * 5);
        oc_memset(stream, 0, 512 * 5);
        tar_build_header(stream, "etc/opencube.conf", 11, '0');
        oc_memcpy(stream + 512, "HELLO-TAR!\0", 11);
        /* trailing two zero end blocks are already zero */
        tar_acc_t acc;
        oc_memset(&acc, 0, sizeof(acc));
        oc_tar_t *t = oc_tar_open(tar_acc_cb, &acc);
        int okt = (t != NULL);
        if (okt) {
            int total = 512 * 5;
            int pos = 0;
            int rc = 0;
            while (pos < total) {
                int take = 100;               /* odd chunks: block assembler */
                if (pos + take > total) take = total - pos;
                rc = oc_tar_feed(t, stream + pos, take);
                if (rc != 0) break;
                pos += take;
            }
            if (rc == 0) rc = oc_tar_finish(t);
            okt = (rc == 0);
        }
        if (okt) okt = (acc.files == 1 &&
                        oc_strcmp(acc.name, "etc/opencube.conf") == 0 &&
                        acc.size == 11 &&
                        oc_strcmp((char *)acc.data, "HELLO-TAR!") == 0);
        char info[96];
        oc_strcpy(info, "files=");
        char num[12];
        oc_u64_to_str((u64)acc.files, num);
        oc_strcat(info, num);
        oc_strcat(info, " name=");
        oc_strcat(info, acc.name);
        oc_console_puts(info);
        oc_console_puts(" ");
        if (t) oc_tar_close(t);
        kfree(stream);
        case_result(okt);
    }
    /* 12: tar checksum corruption rejected */
    {
        case_begin("ustar bad checksum rejected");
        u8 *stream = (u8 *)kmalloc(512 * 4);
        oc_memset(stream, 0, 512 * 4);
        tar_build_header(stream, "x", 0, '0');
        stream[148] ^= 0x01;                       /* corrupt checksum */
        tar_acc_t acc;
        oc_memset(&acc, 0, sizeof(acc));
        oc_tar_t *t = oc_tar_open(tar_acc_cb, &acc);
        int rc = t ? oc_tar_feed(t, stream, 512 * 4) : OC_TAR_ERR_ARGS;
        if (t) oc_tar_close(t);
        kfree(stream);
        case_result(rc == OC_TAR_ERR_CSUM);
    }

    char line[64];
    char num[12];
    oc_strcpy(line, "[update_pkg_test] ");
    oc_u64_to_str((u64)t_pass, num);
    oc_strcat(line, num);
    oc_strcat(line, "/");
    oc_u64_to_str((u64)t_total, num);
    oc_strcat(line, num);
    oc_strcat(line, t_pass == t_total ? " PASS" : " FAIL");
    oc_console_puts(line);
    oc_console_puts("\n");
    return (t_pass == t_total) ? 0 : 1;
}

