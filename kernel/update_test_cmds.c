/* ==================================================================== */
/* real_update_test: end-to-end phase 1                                  */
/* ==================================================================== */

int cmd_real_update_test(const char *args) {
    (void)args;
    t_pass = 0; t_total = 0;
    oc_console_puts("[real_update_test] end-to-end phase 1 "
                    "(download -> install -> set_boot)\n");

    case_begin("A/B disk present");
    int ab = oc_ab_flags_ready();
    case_result(ab);
    if (!ab) return 1;

    case_begin("online_update enabled");
    int en = oc_config_online_update_enabled();
    case_result(en);
    if (!en) return 1;

    case_begin("manifest check (new version)");
    oc_update_pkg_info_t pkg;
    int rc = oc_update_check_pkg(&pkg);
    int ok = (rc == OC_UPDATE_NEW && pkg.have_package);
    case_info("rc=", rc);
    case_result(ok);
    if (!ok) return 1;

    const char *path = OC_UPDATE_PKG_PATH;
    vfs_stat_t st;
    if (vfs_stat("/data", &st) != 0) path = OC_UPDATE_PKG_TMP;

    case_begin("download");
    int n = oc_update_download(pkg.package_url, path);
    case_info("bytes=", n);
    case_result(n > 0);
    if (n <= 0) return 1;

    case_begin("verify sha256");
    rc = oc_update_verify(path, pkg.package_sha256);
    case_result(rc == 0);
    if (rc != 0) return 1;

    case_begin("install into slot B");
    rc = oc_update_install(path, "B");
    case_result(rc == 0);
    if (rc != 0) return 1;

    case_begin("set boot to B");
    rc = oc_update_set_boot("B");
    case_result(rc == 0);
    if (rc != 0) return 1;

    oc_console_puts("[real_update_test] phase 1 complete\n");
    oc_console_puts("[real_update_test] phase 2: reboot, verify slot B "
                    "kernel, then rollback\n");

    char line[64];
    char num[12];
    oc_strcpy(line, "[real_update_test] ");
    oc_u64_to_str((u64)t_pass, num);
    oc_strcat(line, num);
    oc_strcat(line, "/");
    oc_u64_to_str((u64)t_total, num);
    oc_strcat(line, num);
    oc_strcat(line, t_pass == t_total ? " PASS" : " FAIL");
    oc_console_puts(line);
    oc_console_puts("\n");
    return (t_pass == t_total) ? 0 : 1;
}

